export const vocabByCat = (cat: VocabCat) => VOCAB.filter((v) => v.cat === cat);

/** The word bank as lesson notes for the "Ambitious vocabulary" topic */
export function vocabNotes(): string {
  const parts = [
    'Ambitious, **precise** vocabulary is one of the clearest signs of a top-band answer: AO5/AO6 in English Language rewards "extensive and ambitious vocabulary", and Literature examiners reward precise analytical verbs. Precise beats fancy – use a word only when it says exactly what you mean.',
    '**How to learn them:** a few words a day, spaced out. Say the meaning, then use the word in your own sentence. Your sessions and flashcards bring them back before you forget.',
  ];
  for (const [cat, info] of Object.entries(VOCAB_CATS) as [VocabCat, { title: string; use: string }][]) {
    parts.push(`## ${info.title}\n*${info.use}*\n\n| Word | Meaning | Example |\n|---|---|---|\n${vocabByCat(cat).slice(0, 10).map((v) => `| **${v.w}** | ${v.def} | ${v.ex} |`).join('\n')}`);
  }
  parts.push('*The full word bank – every word with its meaning and an example – is on the Vocabulary page.*');
  return parts.join('\n\n');
}
